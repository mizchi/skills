#!/usr/bin/env python3
"""Generate mizchi-skill/references/catalog.md from the skills in this repository.

usage: gen_catalog.py [--root REPO] [--stdout | --check]

Rows come from the README's "## Skills" tables (short, hand-written wording, grouped by area). Skills that the
README does not list are added under "Other" with the first sentences of their SKILL.md description. Skills whose
description says they run only on an explicit request are marked "explicit only", and the router does not load them
on its own. --check exits 1 when the checked-in catalog differs from what would be generated.
"""
import argparse
import os
import re
import sys

SELF = "mizchi-skill"
EXPLICIT = re.compile(r"invoke only when|do not auto-invoke|only when the user explicitly|explicitly asks about", re.I)
ROW = re.compile(r"^\|\s*\[([\w.-]+)\]\([^)]*\)\s*\|\s*`[^`]*`\s*\|\s*(.+?)\s*\|\s*$")
HEADER = """# mizchi/skills catalog

Generated by `scripts/gen_catalog.py` from the repository README and each SKILL.md; do not edit by hand.
Load a skill with `bash scripts/fetch_skill.sh <name>`. Rows marked *explicit only* are loaded only when the user
asks for that skill or its job by name.
"""


def description(path):
    text = open(path, encoding="utf-8").read()
    m = re.match(r"^---\n(.*?)\n---", text, re.S)
    if not m:
        return ""
    fm = m.group(1)
    d = re.search(r"^description:\s*(.*(?:\n[ \t]+.*)*)", fm, re.M)
    if not d:
        return ""
    v = d.group(1).strip()
    if v[:1] in "|>":
        v = " ".join(l.strip() for l in v[1:].splitlines())
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
        v = v[1:-1].replace("''", "'")
    return " ".join(v.split())


def shorten(text, limit=200):
    out = ""
    for s in re.split(r"(?<=[.!?])\s+", text):
        if out and len(out) + len(s) + 1 > limit:
            break
        out = f"{out} {s}".strip()
    return out if len(out) <= limit else out[: limit - 1].rstrip() + "…"


def skills(root):
    found = {}
    for d in sorted(os.listdir(root)):
        p = os.path.join(root, d, "SKILL.md")
        if d.startswith((".", "_")) or d == SELF or not os.path.isfile(p):
            continue
        found[d] = description(p)
    return found


def readme_groups(root):
    groups, cur, on = [], None, False
    p = os.path.join(root, "README.md")
    if not os.path.isfile(p):
        return groups
    for line in open(p, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("## "):
            on = line.strip() == "## Skills"
            continue
        if not on:
            continue
        if line.startswith("### "):
            cur = (line[4:].strip(), [])
            groups.append(cur)
        elif cur is not None:
            m = ROW.match(line)
            if m:
                cur[1].append((m.group(1), m.group(2)))
    return groups


def render(root):
    all_skills = skills(root)
    seen, parts = set(), [HEADER]

    def row(name, text):
        flag = " (explicit only)" if EXPLICIT.search(all_skills.get(name, "")) else ""
        return f"| `{name}` | {text.replace('|', '/')}{flag} |"

    for title, rows in readme_groups(root):
        rows = [(n, t) for n, t in rows if n in all_skills and n not in seen]
        if not rows:
            continue
        parts.append(f"\n### {title}\n\n| Skill | Use for |\n| --- | --- |")
        for n, t in rows:
            seen.add(n)
            parts.append(row(n, t))
    rest = [n for n in all_skills if n not in seen]
    if rest:
        parts.append("\n### Other\n\n| Skill | Use for |\n| --- | --- |")
        parts.extend(row(n, shorten(all_skills[n])) for n in rest)
    return "\n".join(parts) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--stdout", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(a.root)
    path = os.path.join(a.root, SELF, "references", "catalog.md")
    if a.stdout:
        sys.stdout.write(text)
    elif a.check:
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if current != text:
            print(f"{path} is stale: run python3 {SELF}/scripts/gen_catalog.py", file=sys.stderr)
            sys.exit(1)
    else:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


if __name__ == "__main__":
    main()
